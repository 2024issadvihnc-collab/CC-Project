  cat === "all" ? events : events.filter((e) => e.category === cat);

export const getEventsByCity = (city, cat = "all") =>
  getEventsByCategory(cat).filter((e) =>
    !city || city === "All" || city === "All Cities" ? true : e.city.toLowerCase() === city.toLowerCase()
  );

